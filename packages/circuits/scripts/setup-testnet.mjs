// Testnet trusted setup: SINGLE PARTY, NOT FOR MAINNET.
//
// One process generates the powers of tau, contributes once with fresh random entropy,
// runs the circuit-specific phase 2 with a second random contribution, and discards the
// entropy. Whoever ran it could forge proofs, so it only guards testnet value. Mainnet
// uses a public multi-party ceremony (docs/vault-spec.md section 8).
//
// Usage: node scripts/setup-testnet.mjs ptau        # phase 1 (slow, once)
//        node scripts/setup-testnet.mjs circuits    # phase 2, verifiers, artifacts
import { createHash, randomBytes } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as snarkjs from "snarkjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contractsDir = join(root, "..", "contracts", "src", "vault", "verifiers");
const POWER = 16;
const LABEL = "Curveil testnet single-party setup (not for mainnet)";
const CIRCUITS = [
  { name: "transfer", contract: "TransferVerifier", schema: "transfer/v1" },
  { name: "withdraw", contract: "WithdrawVerifier", schema: "withdraw/v1" },
];

const ptauDir = join(root, "ptau");
const ptauFinal = join(ptauDir, `pot${POWER}_final.ptau`);
const sha256 = (path) => createHash("sha256").update(readFileSync(path)).digest("hex");
// Entropy never touches disk or argv; it is dropped when the process exits.
const entropy = () => randomBytes(64).toString("hex");
const logger = { log: () => {}, info: () => {}, debug: () => {}, warn: console.warn, error: console.error };

async function ptau() {
  mkdirSync(ptauDir, { recursive: true });
  const curve = await snarkjs.curves.getCurveFromName("bn128");
  const p0 = join(ptauDir, `pot${POWER}_0000.ptau`);
  const p1 = join(ptauDir, `pot${POWER}_0001.ptau`);
  console.log(`phase 1: new accumulator 2^${POWER}`);
  await snarkjs.powersOfTau.newAccumulator(curve, POWER, p0, logger);
  console.log("phase 1: contribution");
  await snarkjs.powersOfTau.contribute(p0, p1, LABEL, entropy(), logger);
  console.log("phase 1: prepare phase 2");
  await snarkjs.powersOfTau.preparePhase2(p1, ptauFinal, logger);
  await curve.terminate();
  console.log(`ptau sha256 ${sha256(ptauFinal)}`);
}

async function circuits() {
  if (!existsSync(ptauFinal)) throw new Error("run the ptau stage first");
  const outDir = join(root, "artifacts", "testnet");
  mkdirSync(outDir, { recursive: true });
  mkdirSync(contractsDir, { recursive: true });
  const templates = { groth16: readFileSync(join(root, "node_modules", "snarkjs", "templates", "verifier_groth16.sol.ejs"), "utf8") };
  const record = {
    label: LABEL,
    network: "testnet",
    createdAt: new Date().toISOString(),
    compiler: "circom 2.2.3 (circom2 npm 0.2.23)",
    snarkjs: "0.7.6",
    ptau: { power: POWER, sha256: sha256(ptauFinal), contributions: 1 },
    circuits: {},
  };
  for (const c of CIRCUITS) {
    const build = join(root, "build", c.name);
    const r1cs = join(build, `${c.name}.r1cs`);
    const wasm = join(build, `${c.name}_js`, `${c.name}.wasm`);
    const z0 = join(build, `${c.name}_0000.zkey`);
    const zkey = join(outDir, `${c.name}.zkey`);
    console.log(`${c.name}: phase 2`);
    await snarkjs.zKey.newZKey(r1cs, ptauFinal, z0, logger);
    await snarkjs.zKey.contribute(z0, zkey, LABEL, entropy(), logger);
    if (!(await snarkjs.zKey.verifyFromR1cs(r1cs, ptauFinal, zkey, logger))) throw new Error(`${c.name}: zkey failed verification`);
    const vkey = await snarkjs.zKey.exportVerificationKey(zkey, logger);
    writeFileSync(join(outDir, `${c.name}.vkey.json`), JSON.stringify(vkey, null, 2) + "\n");
    copyFileSync(wasm, join(outDir, `${c.name}.wasm`));

    let sol = await snarkjs.zKey.exportSolidityVerifier(zkey, templates, logger);
    sol = sol
      .replace("pragma solidity >=0.7.0 <0.9.0;", "pragma solidity 0.8.28;")
      .replace("contract Groth16Verifier {", `/// @notice Generated by snarkjs 0.7.6 from ${c.name}.zkey (${LABEL}). Do not edit.\n///         Public-input schema: ${c.schema}.\ncontract ${c.contract} {`);
    writeFileSync(join(contractsDir, `${c.contract}.sol`), sol);

    record.circuits[c.name] = {
      schema: c.schema,
      nPublic: vkey.nPublic,
      r1cs: sha256(r1cs),
      wasm: sha256(wasm),
      zkey: sha256(zkey),
      vkey: sha256(join(outDir, `${c.name}.vkey.json`)),
      verifier: c.contract,
    };
    console.log(`${c.name}: ok, ${vkey.nPublic} public inputs`);
  }
  writeFileSync(join(outDir, "setup.json"), JSON.stringify(record, null, 2) + "\n");
  console.log("wrote artifacts/testnet/setup.json");
}

const stage = process.argv[2];
if (stage === "ptau") await ptau();
else if (stage === "circuits") await circuits();
else throw new Error("usage: setup-testnet.mjs ptau|circuits");
process.exit(0);
